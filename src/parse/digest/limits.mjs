/**
 * 時系列を組むときの上限と、上限を超えたときに落とす順。
 *
 * 数字だけをここに集めてある。調整するときに buildDigest の中を読まなくて済むように。
 * どれも「どこで切るか」の判断であって、意味を持つ境目ではない。
 */
import { MAX_DETAIL } from '../../shared/tools.mjs';

/** 1件あたりの上限。判断の記録になるものは長めに残し、説明文は短くする。 */
export const LIMIT = {
  prompt: 6000,
  say: 1200,
  // 最後の1件だけの上限。「いま」タブの待ちブロックが出す最後の応答が
  // 「…（以下省略）」で切れると、答えるための材料がその場で足りなくなる。
  // プラン（承認の判断に使う）と同じ幅にしてある。
  //
  // **say そのものを上げてはいけない。** 実測（20ログ・assistant text 2,639件）で
  // 1200 超は 166件（6.29%）あり、上限を 4000 にすると say の総量が +20.3%、
  // 切らないと +31.0% になる。経過タブには数十件並ぶので応答がまるごと膨らむ。
  // 最後の1件だけなら増分は実質ゼロ（1本あたり中央 2,876字・最大 48,237字の中の1件）
  sayLast: 24000,
  plan: 24000,
  // 中間報告は Claude が自分で畳んだ文なので、もともと長くない。発言より少しだけ広く取る
  recap: 2000,
  // ツールの一行説明と同じ長さ。並べて出るものなので揃える
  detail: MAX_DETAIL,
  feedback: 2000,
};

/** 時系列に並べる項目の上限。超えたら古い説明文から落とす。 */
export const MAX_ITEMS = 400;

/**
 * 足跡（trace）だけの独立枠。
 *
 * 足跡は件数の桁が他と違うので、本編と同じ枠で取り合わせると
 * 足跡が残って Claude の説明が消える、という一番いやな壊れ方が起きる。
 * 既定では隠れている項目なので、本編を圧迫させない
 */
export const MAX_TRACES = 200;

/**
 * 足跡に残す結果の先頭の長さ。
 *
 * 本文は積まない。足跡が答えるのは「どこを見に行ったか」で、
 * 結果の中身が要るときは原文（/api/sessions/:id/entry/:uuid）に戻ればよい。
 * 200件ぶんの全文を載せると詳細の応答が桁で膨らむ
 */
export const TRACE_HEAD = 160;

/**
 * 上限を超えたときに落とす順。前のほうから使い切る。
 *
 * ここに無い種類は落とさない。指示・選択・プラン・却下・圧縮などの判断の記録がそれで、
 * 将来ここに知らない種類が増えても既定で残る側に倒れる
 */
export const DROP_ORDER = [
  ['error'],           // 件数は stats.errors に残る
  ['skill', 'agent'],  // skills / agents 配列と同じ参照なので、そちらに残る
  ['say'],             // ここまで来たら諦める
];

/** ファイルを書き換えるツール。「触ったファイル」の判定に使う。 */
export const WRITE_TOOLS = new Set(['Edit', 'Write', 'NotebookEdit', 'MultiEdit']);

/**
 * 4時間。これより長い待ちは「考えていた時間」ではなく席を外していた時間と見る。
 *
 * 境目に根拠があるわけではない。ただ、昼をまたいだ空白を「回答までの間」として
 * 合計に混ぜると集計が意味を失うので、別枠に寄せる線をどこかに引く必要がある
 */
export const AWAY_MS = 4 * 60 * 60 * 1000;
